// Writes source/model/EscapeDebugTables.cpp: the code point ranges that Rust's `str::escape_debug`
// writes as `\u{...}`, read off the running toolchain's own implementation. "Always" ranges are
// escaped at any position; "leading" ranges (grapheme extenders) only as the first character.
use std::fmt::Write;

fn unicode_escaped(s: &str) -> bool {
    s.starts_with("\\u{")
}

fn escaped_after_first(c: char) -> String {
    format!("a{c}").escape_debug().skip(1).collect()
}

fn ranges(predicate: impl Fn(char) -> bool) -> Vec<(u32, u32)> {
    let mut out: Vec<(u32, u32)> = Vec::new();
    for code_point in 0u32..=0x10FFFF {
        let Some(c) = char::from_u32(code_point) else { continue };
        if !predicate(c) {
            continue;
        }
        match out.last_mut() {
            Some(last) if last.1 + 1 == code_point => last.1 = code_point,
            _ => out.push((code_point, code_point)),
        }
    }
    out
}

fn table(out: &mut String, name: &str, ranges: &[(u32, u32)]) {
    writeln!(out, "constexpr std::array<CodePointRange, {}> {name}{{{{", ranges.len()).unwrap();
    for (first, last) in ranges {
        writeln!(out, "    {{0x{first:x}, 0x{last:x}}},").unwrap();
    }
    writeln!(out, "}}}};").unwrap();
}

fn main() {
    let always = ranges(|c| unicode_escaped(&escaped_after_first(c)));
    let leading = ranges(|c| {
        let first: String = c.to_string().escape_debug().collect();
        unicode_escaped(&first) && !unicode_escaped(&escaped_after_first(c))
    });
    let version = std::env::var("ESCAPE_DEBUG_TABLES_RUSTC_VERSION").unwrap_or_default();

    let mut out = String::new();
    writeln!(out, "// Generated by scripts/generate-escape-debug-tables.sh from {version}. Do not edit.").unwrap();
    writeln!(out, "#include \"model/EscapeDebugTables.hpp\"\n").unwrap();
    writeln!(out, "#include <array>\n").unwrap();
    writeln!(out, "namespace cedar::detail\n{{\n\nnamespace\n{{\n").unwrap();
    table(&mut out, "AlwaysEscapedRanges", &always);
    writeln!(out).unwrap();
    table(&mut out, "LeadingEscapedRanges", &leading);
    writeln!(out, "\n}} // namespace\n").unwrap();
    writeln!(out, "auto EscapeDebugAlwaysEscapedRanges() -> std::span<const CodePointRange>\n{{\n    return AlwaysEscapedRanges;\n}}\n").unwrap();
    writeln!(out, "auto EscapeDebugLeadingEscapedRanges() -> std::span<const CodePointRange>\n{{\n    return LeadingEscapedRanges;\n}}\n").unwrap();
    writeln!(out, "}} // namespace cedar::detail").unwrap();
    print!("{out}");
}
